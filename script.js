'use strict';
const ideas = [
  'Найди вокруг пять предметов одного цвета. Составь из них свою маленькую палитру.',
  'Нарисуй предмет рядом с собой одной непрерывной линией, не отрывая карандаш от бумаги.',
  'Придумай три новых применения обычной картонной коробке.',
  'Послушай минуту окружающие звуки. Попробуй назвать каждый из них.',
  'Сфотографируй необычную тень и придумай название этому маленькому произведению.',
  'Выбери слово из книги и напиши короткую историю из трёх предложений с этим словом.'
];
let current = 0;
document.getElementById('shuffle').addEventListener('click', () => {
  current = (current + 1 + Math.floor(Math.random() * (ideas.length - 1))) % ideas.length;
  document.getElementById('prompt').textContent = ideas[current];
});
